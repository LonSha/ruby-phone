#!/usr/bin/env node
/**
 * gen_time_debt_readings.mjs —— R21-O2 时间欠债机器读数（规格唯一指定生成器）
 *
 * 扫 tests/fixtures/bare-now-whitelist.json 里每条理由文本，分三列计数：
 *   1. story 档已收口 —— 文本含「【R21-O2 已收口】」，或含历史批次收口叙述（
 *      「已于 v4.140.0 改走」「已于 v4.140.0 收口」「已无裸 `Date.now()`」）；
 *   2. story 档待收口 —— 文本含「待收口」字样（欠债清零后应为 0）；
 *   3. wall 档合法 —— 其余条目（幂等键/节流/真实耗时等，本来就不该跟剧情钟）。
 *
 * 输出 tests/audit/time_debt_readings.json。判据 tests/system-v4141.test.mjs ④
 * 要求生成器读数与磁盘逐字一致（防手抄）。
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const whitelistPath = join(root, "tests/fixtures/bare-now-whitelist.json");
const outPath = join(root, "tests/audit/time_debt_readings.json");

const wl = JSON.parse(readFileSync(whitelistPath, "utf8"));
const entries = Object.entries(wl.files || {});

let storyClosed = 0;
let storyPending = 0;
let wallLegal = 0;
const pendingFiles = [];
const closedFiles = [];

for (const [file, note] of entries) {
  const text = String(note);
  if (text.includes("待收口")) {
    storyPending += 1;
    pendingFiles.push(file);
  } else if (
    text.includes("【R21-O2 已收口】") ||
    text.includes("已于 v4.140.0 收口") ||
    text.includes("已于 v4.140.0 改走") ||
    text.includes("已无裸 `Date.now()`")
  ) {
    storyClosed += 1;
    closedFiles.push(file);
  } else {
    wallLegal += 1;
  }
}

const readings = {
  schema: "time-debt-readings@1",
  version: wl.version,
  total: entries.length,
  storyClosed,
  storyPending,
  wallLegal,
  pendingFiles,
  closedFiles,
  generatedAt: "由判据强制与磁盘一致，本字段仅说明生成来源：tools/gen_time_debt_readings.mjs",
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(readings, null, 2) + "\n", "utf8");

// 运行时同源模块：诊断台（apps/clock/clock-view.js）import 用。
// 单一事实来源仍是本生成器 —— 手改本文件会被判据④「与磁盘逐字一致」抓住。
const runtimePath = join(root, "config/time-debt-readings.js");
const runtimeSrc = `/* AUTO-GENERATED by tools/gen_time_debt_readings.mjs —— 勿手改（判据 tests/system-v4141.test.mjs ④ 防手抄） */
/* R21-O2 时间欠债读数：白名单 ${entries.length} 条 = story 已收口 ${storyClosed} / story 待收口 ${storyPending} / wall 档合法 ${wallLegal} */
export const TIME_DEBT_READINGS = Object.freeze({
  schema: "time-debt-readings@1",
  version: ${JSON.stringify(wl.version)},
  total: ${entries.length},
  storyClosed: ${storyClosed},
  storyPending: ${storyPending},
  wallLegal: ${wallLegal},
  closedFiles: Object.freeze(${JSON.stringify(closedFiles)}),
  pendingFiles: Object.freeze(${JSON.stringify(pendingFiles)}),
});
`;
writeFileSync(runtimePath, runtimeSrc, "utf8");
console.log(`[gen_time_debt_readings] total=${readings.total} storyClosed=${storyClosed} storyPending=${storyPending} wallLegal=${wallLegal} -> ${outPath} + ${runtimePath}`);