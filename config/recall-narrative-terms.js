/* ========================================================
 * config/recall-narrative-terms.js — [v4.111.0 · R13-X8] 复述的词表与口径（纯数据，零 import）
 * --------------------------------------------------------
 * 【为什么词表要单独一件】主件算法只有一百多行，词表与停用词占了一半体积。
 *   本仓的硬约束是「新内核单件 ≤ 12K，超出必须拆」；拆词表是**唯一不损伤算法**的切法：
 *   改停用词不必碰归并规则，改归并规则不必读停用词。
 *
 * 【这一件守的是什么】它只放「什么算空话」与「什么算同一件事」这两组口径。
 *   这两组都是**会被人反复调整**的东西（用户说「这个话题不该出现」，改的是这里），
 *   把它们与算法分开，才能保证调整不会动到「引用必须真实」那条铁律。
 * ============================================================ */
'use strict';

/** 复述的两种结局：**不是**布尔 —— 「没找到」与「找不出能归并的」处置相反。 */
export const RECALL_NARRATIVE_STATES = Object.freeze({
    ok: 'ok',              /* 有 episode 且全部通过引用核对 */
    empty: 'empty',        /* 主题确实没在聊天里出现过（不是读不出来） */
    unreadable: 'unreadable' /* 聊天读不出来 —— 与 empty 不同形，不许同形 */
});

/**
 * 归并失败的三种因由（闭集）。
 * 「没能归并」是个**结果**，不是一个理由；用户要知道是「一条都没有」还是「有但拆不开」。
 */
export const RECALL_NARRATIVE_GAPS = Object.freeze({
    NO_CHAT: 'no-chat',                 /* 宿主没给聊天数组 */
    NO_TOPIC: 'no-topic',               /* 主题是空的 / 全是停用词 */
    NO_MATCH: 'no-match',               /* 聊天里没有一句沾这个话题 */
    NO_MERGE: 'no-merge',               /* 有命中但彼此隔得太远，各自独立成一段 */
    BAD_ID: 'bad-id'                    /* 有条目拿不到真实 id（该条不交出去） */
});

/**
 * 停用词：**不参与主题匹配**的词。
 * 为什么要：「我们之前聊过搬家的事吗」里的「我们/之前/聊过/的事/吗」在每一段聊天里都有，
 *   拿它们当主题词等于没筛（与 X2 那条「单字不当条件」同一个道理）。
 * 有一条纪律：本表**只放虚词**，不放任何实义名词 —— 放进去就等于剥夺用户用这个词找回忆的权利。
 */
export const RECALL_STOPWORDS = Object.freeze([
    '我们', '咱们', '你们', '他们', '她们', '它们',
    '之前', '以前', '后来', '当时', '那时候', '那次', '上次', '上回',
    '聊过', '说过', '提过', '讲过', '谈到', '说起',
    '什么', '怎么', '为什么', '哪个', '哪些', '哪次', '多少',
    '事情', '的事', '东西', '那个', '这个', '那些', '这些',
    '还有', '然后', '但是', '不过', '而且', '因为', '所以',
    '记得', '好像', '大概', '是不是', '有没有',
    '一下', '一个', '一些', '有点', '一直', '还是', '就是',
    '吗', '呢', '吧', '啊', '呀', '哦', '嗯', '的话'
].sort((a, b) => b.length - a.length));

/**
 * `msgs` 的下限与上限。
 * 下限 1：一条也能算「提过这件事」（宁可复述得笨，不许复述得假）。
 * 上限 12：一段 episode 引用超过十几条，用户点回去也看不清是哪句 —— 那不是复述，那是丢一段记录。
 */
export const RECALL_LIMITS = Object.freeze({
    minMsgs: 1,
    maxMsgs: 12,
    /** 主题词的最短长度（低于此长度不当主题词：「雨」这类单字在每段聊天里都可能出现）。 */
    minTopicLen: 2,
    /** 两段命中的**楼层间隔**阈值：间隔小于它视为同一段（同一场对话里连着说的）。 */
    mergeGapFloors: 6,
    /** 同一段里相邻两条之间的**时间间隔**阈值（毫秒）：超过它即使楼层相邻也断开。 */
    mergeGapMs: 45 * 60 * 1000,
    /** `conclusion` 的长度上限（截取最后一条命中的一段话，不生成新句子）。 */
    conclusionMaxChars: 120
});

/**
 * 排序与取舍用的固定顺序（写在数据里而不是散在算法里，判据才能逐项核）。
 */
export const RECALL_ORDER = Object.freeze({
    /** episode 排序：时间倒序（最近的一段先给）。同一时刻按首条楼层升序兜底，保证确定性。 */
    byRecentFirst: true
});
