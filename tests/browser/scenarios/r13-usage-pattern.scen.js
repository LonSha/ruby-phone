import { mountUsagePattern } from '/apps/settings/usage-pattern-section.js';
import { PhoneStorage } from '/config/storage.js';
import { getUsagePattern } from '/config/usage-pattern.js';
import { trackerNote, trackerClose } from '/config/usage-tracker.js';
const root = document.createElement('main');
root.innerHTML = '<div id="tab-general"><p id="existing-setting">既有设置</p></div>';
root.style.cssText = 'width:100%;max-width:420px;box-sizing:border-box;padding:12px;font:14px sans-serif';
document.body.append(root);
const storage = Object.create(PhoneStorage.prototype);
const legacy = new Map();
storage.get = (key, fallback) => legacy.get(key) ?? fallback;
storage.set = (key, value) => legacy.set(key, value);
const chat = { role: 'untouched' }, global = { theme: 'untouched' };
storage._getChatMetadataStore = () => chat;
storage._getExtensionSettingsStore = () => global;
window.confirm = () => true;
const before = JSON.stringify([chat, global]);
mountUsagePattern(root, storage);
const off = root.querySelector('[data-usage-enabled]');
report({name:'default-off',ok:off && !off.checked && root.querySelectorAll('details').length===0,detail:'default hidden aggregate rows'});
off.checked=true;off.dispatchEvent(new Event('change',{bubbles:true}));
trackerNote(storage,'wechat',1700000000000);trackerClose(storage,1700000001000);
mountUsagePattern(root,storage);
let ack=root.querySelector('[data-usage-ack="wechat"]');
report({name:'trace-shown',ok:ack && !ack.disabled,detail:'existing tracker drives device aggregate'});
ack.click();
report({name:'acknowledge-roundtrip',ok:getUsagePattern(storage).trace('wechat').acknowledged && root.textContent.includes('已承认这份痕迹'),detail:'button writes and rerenders'});
mountUsagePattern(root,storage);
report({name:'reopen-enabled',ok:root.querySelector('[data-usage-enabled]').checked,detail:'local setting survives remount'});
root.querySelector('[data-usage-clear]').click();
report({name:'clear-roundtrip',ok:getUsagePattern(storage).trace('wechat').state==='never',detail:'clear resets counts'});
const toggle=root.querySelector('[data-usage-enabled]');toggle.checked=false;toggle.dispatchEvent(new Event('change'));
report({name:'off-hides-rows',ok:root.querySelectorAll('details').length===0 && root.querySelector('#existing-setting').textContent==='既有设置',detail:'no existing setting is replaced'});
report({name:'role-buckets-unchanged',ok:JSON.stringify([chat,global])===before,detail:'exportable buckets unchanged byte-for-byte'});
const button=root.querySelector('[data-usage-clear]');button.scrollIntoView({block:'center'});
const rect=button.getBoundingClientRect();const hit=document.elementFromPoint(rect.left+rect.width/2,rect.top+rect.height/2);
report({name:'clear-hit-test',ok:rect.width>0 && rect.height>0 && (hit===button || button.contains(hit)),detail:'visible and hit-testable'});
report({name:'narrow-no-overflow',ok:root.scrollWidth<=root.clientWidth+1,detail:`scroll=${root.scrollWidth},client=${root.clientWidth}`});
done();