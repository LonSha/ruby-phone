import { SharedChoreView } from '/apps/affairs/shared-chore-view.js';
import { readChores } from '/config/shared-chore-store.js';
const data = new Map();
const app = { storage: { get: k => data.get(k), set: (k,v) => data.set(k,v) } };
const container = document.createElement('main'); document.body.append(container);
const view = new SharedChoreView(app); view.render(container);
const form = container.querySelector('form');
form.elements.title.value = '聚餐准备'; form.elements.members.value = '甲\n乙';
form.elements.tasks.value = '买菜｜乙\n订位｜甲'; form.elements.amount.value = '1.01';
form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
report({ name: 'create-from-form', ok: readChores(app.storage).rows.length === 1, detail: 'real form submit, chat storage fixture' });
container.querySelector('[data-op="finish"]').click();
const read = readChores(app.storage);
report({ name: 'partial-and-receipt', ok: read.rows[0]?.state === 'partial' && !!read.rows[0]?.tasks[0].completedAt, detail: 'one task completed; second retained' });
view.render(container);
report({ name: 'refresh-preserves', ok: container.textContent.includes('部分完成') && container.textContent.includes('尚未付款'), detail: 'redrawn from persisted records' });
container.querySelector('[data-op="cancel"]').click();
report({ name: 'cancel-blocks-finance', ok: !container.querySelector('[data-op="finance"]') && readChores(app.storage).rows[0].state === 'cancelled', detail: 'cancelled item has no finance button' });
done();